#!/usr/bin/env python3
"""
Generates everything the Switch build needs from a (patched) Ren'Py 8.5
source tree, using Ren'Py's own build helpers (scripts/setuplib.py):

  * the statically-linkable Cython C sources (tmp/gen3-static/*.c),
  * <out>/renpy_modules.cmake  - list of C sources for CMake,
  * <out>/renpy_inittab.h      - PyInit_* declarations + inittab entries.

Usage (from anywhere):

    RENPY_CYTHON=cython python3 switch_modules.py <renpy-source> <out-dir>

The module list mirrors renpy-8.5.x/setup.py, minus what the Switch cannot
use:
  * renpy.gl2.assimp   (needs the assimp C++ library; a Python stub is used)
  * renpy.tfd          (desktop file dialogs; Ren'Py imports it optionally)
  * renpy.gl2.live2dmodel (needs the proprietary Cubism SDK)
"""

import os
import sys

if len(sys.argv) != 3:
    print(__doc__)
    sys.exit(2)

RENPY = os.path.abspath(sys.argv[1])
OUT = os.path.abspath(sys.argv[2])

os.environ["RENPY_STATIC"] = "1"
os.environ.setdefault("RENPY_CYTHON", "cython")

os.chdir(RENPY)
sys.path.insert(0, os.path.join(RENPY, "scripts"))

import setuplib  # noqa: E402
from setuplib import cython  # noqa: E402
import generate_styles  # noqa: E402

setuplib.init()
generate_styles.generate()

# name -> extra C sources (paths relative to the Ren'Py source root).
cython("_renpy", ["src/IMG_savepng.c", "src/core.c"])

cython("renpy.astsupport")
cython("renpy.cslots")
cython("renpy.lexersupport")
cython("renpy.pydict")
cython("renpy.style")
cython("renpy.encryption")

cython("renpy.audio.renpysound", ["src/renpysound_core.c", "src/ffmedia.c"])
cython("renpy.audio.filter")

cython("renpy.styledata.styleclass")
cython("renpy.styledata.stylesets")

for p in generate_styles.prefixes:
    cython(
        "renpy.styledata.style_{}functions".format(p),
        pyx=setuplib.gen + "/style_{}functions.pyx".format(p),
    )

cython("renpy.display.matrix")
cython("renpy.display.render")
cython("renpy.display.accelerator")
cython("renpy.display.quaternion")

cython("renpy.uguu.gl")
cython("renpy.uguu.uguu")

cython("renpy.gl2.gl2mesh")
cython("renpy.gl2.gl2mesh2")
cython("renpy.gl2.gl2mesh3")
cython("renpy.gl2.gl2polygon")
cython("renpy.gl2.gl2model")
cython("renpy.gl2.gl2draw")
cython("renpy.gl2.gl2texture")
cython("renpy.gl2.gl2uniform")
cython("renpy.gl2.gl2shader")

cython("renpy.text.textsupport")
cython("renpy.text.texwrap")
cython("renpy.text.ftfont", ["src/ftsupport.c", "src/ttgsubtable.c"])
cython("renpy.text.hbfont", ["src/ftsupport.c"])
cython("renpy.text.bidi", ["src/renpybidicore.c"])

cython("renpy.pygame.error")
cython("renpy.pygame.color")
cython("renpy.pygame.controller")
cython("renpy.pygame.rect")
cython("renpy.pygame.rwobject")
cython("renpy.pygame.surface", ["src/pygame/alphablit.c"])
cython("renpy.pygame.display")
cython("renpy.pygame.event")
cython("renpy.pygame.locals")
cython("renpy.pygame.key")
cython("renpy.pygame.mouse")
cython("renpy.pygame.joystick")
cython("renpy.pygame.power")
cython("renpy.pygame.pygame_time")
cython("renpy.pygame.image", ["src/pygame/write_jpeg.c", "src/pygame/write_png.c"])
cython("renpy.pygame.transform", ["src/pygame/SDL2_rotozoom.c"])
cython("renpy.pygame.gfxdraw", ["src/pygame/SDL_gfxPrimitives.c"])
cython("renpy.pygame.draw")
cython("renpy.pygame.scrap")

setuplib.generate_all_cython()

# ---------------------------------------------------------------------------
# Emit the CMake source list and the inittab header.

os.makedirs(OUT, exist_ok=True)

sources = []
modules = []

for ext in setuplib.extensions:
    modules.append(ext.name)

    for s in ext.sources:
        path = os.path.normpath(os.path.join(RENPY, s))
        if not os.path.exists(path):
            raise SystemExit("Missing source for {}: {}".format(ext.name, path))
        if path not in sources:
            sources.append(path)

with open(os.path.join(OUT, "renpy_modules.cmake"), "w") as f:
    f.write("# Generated by scripts/switch_modules.py - do not edit.\n")
    f.write("set(RENPY_SOURCE_DIR \"{}\")\n".format(RENPY))
    f.write("set(RENPY_GEN_DIR \"{}\")\n".format(os.path.join(RENPY, setuplib.gen)))
    f.write("set(RENPY_MODULE_SOURCES\n")
    for s in sources:
        f.write("    \"{}\"\n".format(s))
    f.write(")\n")


def init_symbol(name):
    # setuplib's static fix-up renames PyInit_<last> to
    # PyInit_<parent_with_underscores>_<last>; top-level modules keep theirs.
    return "PyInit_" + name.replace(".", "_")


with open(os.path.join(OUT, "renpy_inittab.h"), "w") as f:
    f.write("/* Generated by scripts/switch_modules.py - do not edit. */\n")
    f.write("#pragma once\n#include <Python.h>\n\n")

    for m in modules:
        f.write("PyMODINIT_FUNC {}(void);\n".format(init_symbol(m)))

    f.write("\n#define RENPY_INITTAB_ENTRIES \\\n")
    for m in modules:
        f.write("    {{\"{}\", {}}}, \\\n".format(m, init_symbol(m)))
    f.write("\n")

# Sanity check: every generated C file must export the symbol we expect.
missing = []
for m in modules:
    c_fn = os.path.join(RENPY, setuplib.gen, m + ".c")
    with open(c_fn) as cf:
        code = cf.read()
    if (init_symbol(m) + "(void)") not in code:
        missing.append((m, init_symbol(m)))

if missing:
    for m, sym in missing:
        print("ERROR: {} does not define {}".format(m, sym))
    raise SystemExit(1)

print("{} modules, {} C sources -> {}".format(len(modules), len(sources), OUT))
